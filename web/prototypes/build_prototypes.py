def esc(x) -> str:
    return html.escape(str(x))


def f(value, kind: str) -> str:
    return FORMATS[kind](value)


def count(n: int) -> str:
    """A whole number with a thousands separator (10,000)."""
    return f"{n:,}"


def interval(m: dict, kind: str) -> str:
    return f"{f(m['ci95'][0], kind)} to {f(m['ci95'][1], kind)}"


# ---- the label data each page needs ----


def meter_domain(label: dict) -> tuple:
    """The prototype's dial covers every condition on the label (the site's covers its four)."""
    return M.domain(label, [c["condition_id"] for c in label["conditions"]])



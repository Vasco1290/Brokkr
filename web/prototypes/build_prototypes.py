def versions_line(labs: dict) -> str:
    gens = {
        (lab["generated"]["by"], lab["generated"]["commit"][:7], lab["schema_version"])
        for lab in labs.values()
    }
    by, commit, schema = sorted(gens)[0]
    site = subprocess.run(
        ["git", "rev-parse", "--short=7", "HEAD"], capture_output=True, text=True, cwd=ROOT
    ).stdout.strip()
    dirty = subprocess.run(
        ["git", "status", "--porcelain"], capture_output=True, text=True, cwd=ROOT
    ).stdout.strip()
    mixed = "" if len(gens) == 1 else " (labels made by different versions)"
    return (
        f"Labels: {esc(by)} at commit {commit}, label schema version {schema}{mixed} · "
        f"pages built at commit {site}{' with uncommitted changes' if dirty else ''}"
    )


def verdict(label: dict, lab: dict, cid: str) -> tuple:
    """(kind, icon, text) of the INT8 build's state in a condition."""
    if lab["status"] == "failed":
        return "failed", ICON["INT8 build failed"], "INT8 build failed"
    row = envelope_row(label, lab, cid)
    if row is None:
        return "untested", "–", "reference condition (not judged)"
    return KIND[row["state"]], ICON[row["state"]], row["state"]



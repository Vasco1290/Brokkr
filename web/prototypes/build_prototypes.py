def model_page(labs: dict) -> str:
    label = labs[FEATURED]
    ref, lab = builds(label)
    cond_name = {c["condition_id"]: c["label"] for c in label["conditions"]}
    summary, rule = label["summary"], label["envelope"]["rule"]
    tested = f(summary["tested_conditions"], "int")
    ci_level = f(label["generated"]["ci_level"], "pct0")
    clean_cost = measurement(label, "shrinking_cost", lab, "clean")
    test = next(d for d in label["datasets"] if d["split"] == "test")
    hw = label["hardware"][0]

    def names(ids):
        return ", ".join(esc(cond_name[c]) for c in ids) or "none"

    facts = [
        (
            "Shrinking cost, clean images",
            f'{f(clean_cost["value"], "pts")} <span class="unit">points</span>',
            f"{ci_level} interval {interval(clean_cost, 'pts')}",
            None,
        ),
        (
            "Large shrinking cost",
            f"{f(summary['large_shrinking_cost']['count'], 'int')} of {tested} "
            '<span class="unit">conditions</span>',
            f"whole interval below the {f(rule['large_shrinking_cost_below'], 'pts0')} point line: "
            + names(summary["large_shrinking_cost"]["conditions"]),
            "harm",
        ),
        (
            "Harsh even at full size",
            f"{f(summary['reference_harmful']['count'], 'int')} of {tested} "
            '<span class="unit">conditions</span>',
            "FP32 is harmful there too: " + names(summary["reference_harmful"]["conditions"]),
            None,
        ),
        (
            "Uncertainty signal unreliable",
            f"{f(summary['coverage_failed']['count'], 'int')} of {tested} "
            '<span class="unit">conditions</span>',
            f"coverage below the {f(rule['coverage_min'], 'pct0')} line: "
            + names(summary["coverage_failed"]["conditions"]),
            None,
        ),
    ]
    fact_html = "".join(
        f'<div class="fact"><p class="fact-name">{n}</p>'
        f'<p class="fact-value mono{" v-" + k if k else ""}">{v}</p>'
        f'<p class="fact-note">{note}</p></div>'
        for n, v, note, k in facts
    )

    def chips(ids):
        spans = "".join(f"<span class=chip>{esc(cond_name[c])}</span>" for c in ids)
        return f'<p class="chips">{spans}</p>'

    groups = []
    for state in ("not harmful", "borderline", "harmful", "not tested"):
        lines = [x for x in summary["lines"] if x["state"] == state]
        conds = [c for x in lines for c in x["conditions"]]
        if state == "harmful":
            inner = "".join(
                f'<p class="cause">{esc(CAUSE_TITLE[x["cause"]])}: {f(x["count"], "int")}</p>'
                + chips(x["conditions"])
                for x in lines
            )
        else:
            inner = chips(conds) if conds else '<p class="muted">none</p>'
        title = {
            "not harmful": "Not harmful in our tests",
            "borderline": "Borderline",
            "harmful": "Harmful",
            "not tested": "Not tested",
        }[state]
        # A count only where the label stores it (one line in the group); harmful ones count per cause.
        n_line = lines[0]["count"] if len(lines) == 1 and lines[0]["count"] is not None else None
        count_html = f' <span class="mono count">{f(n_line, "int")}</span>' if n_line is not None else ""
        groups.append(
            f'<div class="group g-{KIND[state]}"><h3><span aria-hidden="true">{ICON[state]}</span> {title}'
            f"{count_html}</h3>{inner}</div>"
        )

    cause_of = {c: x["cause"] for x in summary["lines"] if x["cause"] for c in x["conditions"]}
    rows = []
    for c in label["conditions"]:
        cid = c["condition_id"]
        fp32, int8 = measurement(label, "top1", ref, cid), measurement(label, "top1", lab, cid)
        cost, drop = (
            measurement(label, "shrinking_cost", lab, cid),
            measurement(label, "damage_drop", lab, cid),
        )
        cov, size = measurement(label, "coverage", lab, cid), measurement(label, "mean_set_size", lab, cid)
        row = envelope_row(label, lab, cid) or {"state": None, "shrinking_cost_flags": [], "failed": []}
        flag = (
            ' <span class="v-harm" title="large shrinking cost">⚠ large</span>'
            if "large shrinking cost" in row["shrinking_cost_flags"]
            else ""
        )
        cause = f'<br><span class="muted">{esc(CAUSE_TITLE[cause_of[cid]])}</span>' if cid in cause_of else ""
        failed = (
            f'<br><span class="muted">failed: {esc(", ".join(row["failed"]))}</span>' if row["failed"] else ""
        )
        rows.append(
            f'<tr><th scope="row">{esc(c["label"])}</th><td class="mono">{f(fp32["value"], "pct")}</td>'
            f'<td class="mono">{f(int8["value"], "pct")}</td>'
            f'<td class="mono">{f(cost["value"], "pts")} '
            f'<span class="ci">({interval(cost, "pts")})</span>{flag}</td>'
            + (
                f'<td class="mono">{f(drop["value"], "pts")} '
                f'<span class="ci">({interval(drop, "pts")})</span></td>'
                if drop
                else '<td class="muted">reference</td>'
            )
            + f'<td class="mono">{f(cov["value"], "pct")} · {f(size["value"], "size")}</td>'
            + (
                f'<td class="v-{KIND[row["state"]]}"><span aria-hidden="true">{ICON[row["state"]]}</span> '
                f"{esc(row['state'])}{cause}{failed}</td></tr>"
                if row["state"]
                else '<td class="muted">reference condition</td></tr>'
            )
        )

    address = f"/models/{model_slug(label)}/{build_slug(lab)}/"
    limits = " ".join([esc(x) for x in label["limits"] if not x.startswith("Measured on one machine")][:2])
    body = f"""
<article class="sheet-page">
  <p class="crumbs"><a href="../../index.html">Catalog</a> / {esc(label["model"]["display_name"])}</p>
  <header class="model-head">
    <h1>{esc(label["model"]["display_name"])}</h1>
    <p class="model-sub">{esc(lab["display_name"])}, compared with {esc(ref["display_name"])}</p>
    <p class="ids"><span class="build-id mono"
      title="Brokkr build ID, generated from the build's address">{build_id(label, lab)}</span>
      <span class="mono addr">{esc(address)}</span>
      <span class="source">{SOURCE_WORDS[label["source"]["kind"]]}</span></p>
  </header>
  <section class="facts" aria-label="Key facts">{fact_html}</section>
  <section aria-labelledby="env-h"><h2 id="env-h">Where the INT8 build holds up</h2>
    <p class="note">Each of the {tested} tested conditions, grouped by the INT8 build's own state;
    harmful ones by cause. Lines: damage drop and coverage, as fixed in the label rules.</p>
    <div class="groups">{"".join(groups)}</div></section>
  <section aria-labelledby="dmg-h"><h2 id="dmg-h">Damage table</h2>
    <div class="sheet scroll"><table class="data sheet-table">
      <thead><tr><th scope="col">Condition</th><th scope="col">FP32 top-1</th><th scope="col">INT8 top-1</th>
      <th scope="col">Shrinking cost (points, {ci_level} interval)</th>
      <th scope="col">INT8 damage drop (points)</th>
      <th scope="col">INT8 coverage · set size</th><th scope="col">INT8 state</th></tr></thead>
      <tbody>{"".join(rows)}</tbody></table></div></section>
  <section class="footnote" aria-label="Test conditions">
    <p><strong>Test conditions.</strong> {esc(test["name"])}, {esc(test["split"])} split,
    {count(test["n_items"])} images per condition; {esc(hw["cpu_model"])}, {esc(hw["os"])}. {limits}</p>
  </section>
</article>"""
    return page(f"{label['model']['display_name']} · Brokkr (prototype)", 2, body, versions_line(labs))



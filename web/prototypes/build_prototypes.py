def visible_numbers(page_html: str) -> list:
    """Every number a reader can see: page text, hover titles, and the data-*-text the switches show."""
    shown = re.findall(r'data-(?:cost-text|interval-text|verdict|label)="([^"]*)"', page_html)
    shown += re.findall(r'title="([^"]*)"', page_html)
    text = re.sub(r"<(script|style|svg)\b.*?</\1>", " ", page_html, flags=re.S)
    svg_text = re.findall(r"<text[^>]*>([^<]*)</text>", page_html)
    text = html.unescape(re.sub(r"<[^>]+>", " ", text))
    return [text, *map(html.unescape, shown), *svg_text]


def check_numbers(pages: dict, labs: dict, domain: tuple, site_commit: str) -> list:
    strings = {s for lab in labs.values() for s in _leaves(lab) if isinstance(s, str) and re.search(r"\d", s)}
    strings |= {s[:7] for s in strings if re.fullmatch(r"[0-9a-f]{40}", s)} | {site_commit}
    strings |= {build_id(lab, builds(lab)[1]) for lab in labs.values()}
    strings |= {f"/models/{model_slug(lab)}/{build_slug(builds(lab)[1])}/" for lab in labs.values()}
    numbers = [
        v
        for lab in labs.values()
        for v in _leaves(lab)
        if isinstance(v, (int, float)) and not isinstance(v, bool)
    ]
    allowed = set()
    for v in numbers:
        for kind, fn in FORMATS.items():
            if kind != "int" or float(v).is_integer():
                allowed |= set(NUMBER.findall(fn(v)))
        if isinstance(v, int):
            allowed |= set(NUMBER.findall(count(v)))
    allowed |= {f"{100 * t:.0f}" for t in meter_ticks(domain)}
    problems = []
    for name, text in pages.items():
        for chunk in visible_numbers(text):
            for s in sorted(strings, key=len, reverse=True) + list(WORDS_WITH_DIGITS) + ["v0", "ImageNet-C"]:
                chunk = chunk.replace(s, " ")
            loose = [t for t in NUMBER.findall(chunk) if t not in allowed]
            if loose:
                problems.append(f"{name}: numbers not in the labels: {sorted(set(loose))[:8]}")
    return problems


def check_meter(checks: dict, labs: dict, domain: tuple) -> list:
    """Re-read the featured label from disk and recompute every needle angle and band."""
    fresh = json.loads((LABELS / FEATURED / "label.json").read_text(encoding="utf-8"))
    ref, lab = builds(fresh)
    problems = []
    for cid, cost, a, band in checks["meter"]:
        m = measurement(fresh, "shrinking_cost", lab, cid)
        if (m["value"], m["ci95"]) != (cost["value"], cost["ci95"]):
            problems.append(f"meter {cid}: value differs from the label")
        if abs(angle(m["value"], domain) - a) > 0.5:
            problems.append(
                f"meter {cid}: needle at {a:.2f} degrees, the value says {angle(m['value'], domain):.2f}"
            )
        if band != arc(m["ci95"][0], m["ci95"][1], domain, R - 4):
            problems.append(f"meter {cid}: interval band does not match the label's interval")
    bars = re.findall(
        r'style="width:([0-9.]+)%"></span></span><span class="mono">([0-9.]+)%</span>', checks["page"]
    )
    for width, printed in bars:  # each bar's length must equal the number printed beside it
        if abs(float(width) - float(printed)) > 0.005:
            problems.append(f"bar width {width}% differs from its printed top-1 {printed}%")
    if not bars:
        problems.append("no table bars found")
    return problems



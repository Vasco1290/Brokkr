PART = re.compile(r"[A-Z]+[0-9.]*(?=[A-Z][a-z]|$)|[A-Z]?[a-z]+[0-9.]*|[0-9.]+[A-Za-z]*")


def model_code(display_name: str) -> str:
    """'MobileNetV3-Large' -> 'MNV3L': split at spaces, hyphens and capitals; a plain word gives its first
    letter, a part with digits or in capitals is kept whole (dots dropped)."""
    code = ""
    for word in re.split(r"[\s-]+", display_name):
        for part in PART.findall(word):
            whole = any(c.isdigit() for c in part) or part.isupper()
            code += part.upper().replace(".", "") if whole else part[0].upper()
    return code


def build_slug(build: dict) -> str:
    """'int8' + 'percentile99.99' -> 'int8-percentile-99.99'; FP32 -> 'fp32'."""
    method = (build.get("recipe") or {}).get("method") or ""
    m = re.fullmatch(r"([a-z]+)([0-9.]*)", method)
    parts = [build["precision"], *(p for p in (m.groups() if m else ()) if p)]
    return "-".join(parts)


def build_id(label: dict, build: dict) -> str:
    """'BRK-' + model code + precision + recipe code (first letter of the method, then its digits)."""
    slug = build_slug(build).split("-")
    recipe = (
        (slug[1][0].upper() + (slug[2].replace(".", "") if len(slug) > 2 else "")) if len(slug) > 1 else ""
    )
    return "-".join(
        p for p in ("BRK", model_code(label["model"]["display_name"]), slug[0].upper(), recipe) if p
    )


def model_slug(label: dict) -> str:
    return label["model"]["name"].replace("_", "-")


# ---- the bench meter (geometry shared by the page and its check) ----

CX, CY, R = 160.0, 158.0, 122.0
SWEEP_FROM, SWEEP = 210.0, 240.0  # degrees: the dial runs from lower left, over the top, to lower right


def meter_domain(label: dict) -> tuple:
    ref, lab = builds(label)
    costs = [measurement(label, "shrinking_cost", lab, c["condition_id"]) for c in label["conditions"]]
    lows = [m["ci95"][0] for m in costs if m] + [label["envelope"]["rule"]["large_shrinking_cost_below"]]
    highs = [m["ci95"][1] for m in costs if m] + [0.0]
    return (math.floor(min(lows) / 0.1) * 0.1, max(0.0, math.ceil(max(highs) / 0.05) * 0.05))


def angle(value: float, domain: tuple) -> float:
    lo, hi = domain
    return SWEEP_FROM - (hi - value) / (hi - lo) * SWEEP


def point(a: float, r: float) -> tuple:
    return CX + r * math.cos(math.radians(a)), CY - r * math.sin(math.radians(a))


def arc(v_from: float, v_to: float, domain: tuple, r: float) -> str:
    """An arc path from the higher value to the lower one (clockwise on screen)."""
    a1, a2 = angle(max(v_from, v_to), domain), angle(min(v_from, v_to), domain)
    (x1, y1), (x2, y2) = point(a1, r), point(a2, r)
    return f"M{x1:.2f} {y1:.2f} A{r:.0f} {r:.0f} 0 {1 if a1 - a2 > 180 else 0} 1 {x2:.2f} {y2:.2f}"


def meter_ticks(domain: tuple) -> list:
    lo, hi = domain
    return [round(k * 0.05, 4) for k in range(math.ceil(lo / 0.05 - 1e-9), math.floor(hi / 0.05 + 1e-9) + 1)]


def meter_svg(label: dict, cost: dict, domain: tuple) -> str:
    line = label["envelope"]["rule"]["large_shrinking_cost_below"]
    lo, hi = domain
    parts = [
        f'<path d="{arc(hi, line, domain, R)}" class="zone zone-small"/>',
        f'<path d="{arc(line, lo, domain, R)}" class="zone zone-large"/>',
    ]
    for t in meter_ticks(domain):
        major = abs(round(t * 100) % 10) == 0
        (x1, y1), (x2, y2) = (
            point(angle(t, domain), R - 10),
            point(angle(t, domain), R - (24 if major else 18)),
        )
        parts.append(
            f'<line x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" '
            f'class="tick{" major" if major else ""}"/>'
        )
        if major:
            x, y = point(angle(t, domain), R - 40)
            parts.append(
                f'<text x="{x:.1f}" y="{y + 5:.1f}" class="tick-label" data-tick="{t}">{100 * t:.0f}</text>'
            )
    for v, name, cls in (
        ((hi + line) / 2, "small", "zone-label"),
        ((line + lo) / 2, "large", "zone-label zone-label-large"),
    ):
        x, y = point(angle(v, domain), R + 14)  # outside the arc, anchored away from it
        anchor = "end" if x < CX - 20 else "start" if x > CX + 20 else "middle"
        parts.append(f'<text x="{x:.1f}" y="{y + 4:.1f}" class="{cls}" text-anchor="{anchor}">{name}</text>')
    parts.append(f'<text x="{CX}" y="{CY + 96}" class="dial-unit">INT8 − FP32, points</text>')
    parts.append(
        f'<path d="{arc(cost["ci95"][0], cost["ci95"][1], domain, R - 4)}" class="band" id="meter-band"/>'
    )
    a = angle(cost["value"], domain)
    parts.append(
        f'<g class="needle" id="meter-needle" style="transform: rotate({-a:.3f}deg)" '
        f'data-angle="{a:.3f}" data-rest="{angle(0.0, domain):.3f}">'
        f'<line x1="{CX - 18}" y1="{CY}" x2="{CX + R - 14}" y2="{CY}"/></g>'
    )
    parts.append(
        f'<circle cx="{CX}" cy="{CY}" r="11" class="hub"/>'
        f'<circle cx="{CX}" cy="{CY}" r="3.5" class="hub-dot"/>'
    )
    return (
        '<svg class="meter-dial" viewBox="-36 0 392 316" role="img" aria-labelledby="meter-title">'
        '<title id="meter-title">Shrinking cost on a dial: needle at the measured value, shaded band '
        "for its interval</title>"
        f'<circle cx="{CX}" cy="{CY}" r="{R + 30}" class="bezel"/>' + "".join(parts) + "</svg>"
    )


